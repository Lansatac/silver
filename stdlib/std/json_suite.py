#!/usr/bin/env python3
"""Writes json_suite.ag from JSONTestSuite's parsing cases (github.com/nst/JSONTestSuite).

    python3 stdlib/std/json_suite.py <JSONTestSuite checkout>

A y_ case must parse, and write back to text that parses to the same value. An n_ case must be
rejected: by parse, or, when its bytes aren't UTF-8, by decode, since a String is always valid
UTF-8 and parse never sees them. An i_ case may go either way, and `undecided` below says which way
std.json goes and why, so a change to one is a decision rather than an accident. `departures` lists
the y_ cases std.json rejects on purpose.
"""
import os
import subprocess
import sys

COMMIT_NOTE = 'JSONTestSuite at {commit}'

# The i_ cases, by what std.json does with them.
undecided = {
    # Numbers: an Int must fit, and a Float too large for one is an error; one too small is zero.
    'i_number_double_huge_neg_exp': 'accept',
    'i_number_huge_exp': 'reject',
    'i_number_neg_int_huge_exp': 'reject',
    'i_number_pos_double_huge_exp': 'reject',
    'i_number_real_neg_overflow': 'reject',
    'i_number_real_pos_overflow': 'reject',
    'i_number_real_underflow': 'accept',
    'i_number_too_big_neg_int': 'reject',
    'i_number_too_big_pos_int': 'reject',
    'i_number_very_big_negative_int': 'reject',
    # Half of a surrogate pair can't be in a String.
    'i_object_key_lone_2nd_surrogate': 'reject',
    'i_string_1st_surrogate_but_2nd_missing': 'reject',
    'i_string_1st_valid_surrogate_2nd_invalid': 'reject',
    'i_string_incomplete_surrogate_and_escape_valid': 'reject',
    'i_string_incomplete_surrogate_pair': 'reject',
    'i_string_incomplete_surrogates_escape_valid': 'reject',
    'i_string_invalid_lonely_surrogate': 'reject',
    'i_string_invalid_surrogate': 'reject',
    'i_string_inverted_surrogates_U+1D11E': 'reject',
    'i_string_lone_second_surrogate': 'reject',
    # A byte-order mark isn't white space, so a document can't start with one.
    'i_structure_UTF-8_BOM_empty_object': 'reject',
    # 500 is within the limit of 512.
    'i_structure_500_nested_arrays': 'accept',
}

# y_ cases std.json rejects on purpose. RFC 8259's grammar allows a key named twice and says only
# that names SHOULD be unique; std.json rejects them, as I-JSON (RFC 7493) does, since parsers that
# disagree about which value wins have been a security problem.
departures = {
    'y_object_duplicated_key': 'reject',
    'y_object_duplicated_key_and_value': 'reject',
}


def silver_string(text):
    """A Silver string literal for `text`, with long runs of a short unit written with `repeat`."""
    pieces = []
    literal = []
    i = 0
    while i < len(text):
        best = None
        for period in range(1, 9):
            unit = text[i:i + period]
            if len(unit) < period:
                break
            count = 1
            while text[i + count * period:i + (count + 1) * period] == unit:
                count += 1
            if period * count >= 64 and (best is None or period * count > best[0] * best[1]):
                best = (period, count)
        if best:
            if literal:
                pieces.append(quote(''.join(literal)))
                literal = []
            period, count = best
            pieces.append(f'{quote(text[i:i + period])}.repeat().take({count}).join("")')
            i += period * count
        else:
            literal.append(text[i])
            i += 1
    if literal or not pieces:
        pieces.append(quote(''.join(literal)))
    return ' ~ '.join(pieces)


def quote(text):
    out = []
    for c in text:
        if c == '"':
            out.append('\\"')
        elif c == '\\':
            out.append('\\\\')
        elif c == '{':
            out.append('\\{')
        elif c == '}':
            out.append('\\}')
        elif ' ' <= c <= '~':
            out.append(c)
        else:
            out.append('\\u{%x}' % ord(c))
    return '"' + ''.join(out) + '"'


def main():
    suite = sys.argv[1]
    cases = os.path.join(suite, 'test_parsing')
    commit = subprocess.run(['git', '-C', suite, 'rev-parse', 'HEAD'],
                            capture_output=True, text=True, check=True).stdout.strip()
    with open(os.path.join(suite, 'LICENSE')) as f:
        license_text = f.read().strip()
    names = sorted(n[:-len('.json')] for n in os.listdir(cases) if n.endswith('.json'))
    missing = [n for n in names if n.startswith('i_') and n not in undecided
               and not is_utf8(os.path.join(cases, n + '.json'))]
    out = [
        f'// Generated by json_suite.py from {COMMIT_NOTE.format(commit=commit)}. Don\'t edit it by hand.',
        '//',
    ]
    out += ['// ' + line if line else '//' for line in license_text.splitlines()]
    out += [
        '',
        'import std.json',
        'import std.range',
        'import std.string',
        '',
        '// It parses, and what it parses to writes back as text that parses to the same value.',
        'def accepts(text: String): Bool {',
        '    if val value = parse(text) {',
        '        if val written = write(value) {',
        '            return parse(written) == Ok(value)',
        '        }',
        '    }',
        '    false',
        '}',
        '',
        'def rejects(text: String): Bool => match parse(text) {',
        '    Ok(_) => false',
        '    Error(_) => true',
        '}',
        '',
    ]
    unknown = []
    for name in names:
        with open(os.path.join(cases, name + '.json'), 'rb') as f:
            data = f.read()
        kind = name[:2]
        try:
            text = data.decode('utf-8')
        except UnicodeDecodeError:
            text = None
        out.append(f'test "{name}" {{')
        if text is None:
            if kind == 'y_':
                sys.exit(f'{name} must parse but isn\'t UTF-8')
            listed = ', '.join(f'0x{b:02x}' for b in data)
            out.append(f'    expect(decode([{listed}]) == None)')
        else:
            if name in departures:
                verdict = departures[name]
            elif kind == 'y_':
                verdict = 'accept'
            elif kind == 'n_':
                verdict = 'reject'
            else:
                verdict = undecided.get(name)
                if verdict is None:
                    unknown.append(name)
                    verdict = 'accept'
            check = 'accepts' if verdict == 'accept' else 'rejects'
            out.append(f'    expect({check}({silver_string(text)}))')
        out.append('}')
        out.append('')
    if unknown:
        sys.exit('no decision for: ' + ', '.join(unknown))
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'json_suite.ag')
    with open(target, 'w', newline='\n') as f:
        f.write('\n'.join(out).rstrip('\n') + '\n')
    print(f'wrote {len(names)} cases to {target}')


def is_utf8(path):
    with open(path, 'rb') as f:
        try:
            f.read().decode('utf-8')
            return True
        except UnicodeDecodeError:
            return False


if __name__ == '__main__':
    main()
